// Copies the MCP Apps bridge bundle the widget imports into a module, so the api host serves it instead of a
// CDN (security audit B3). Run after upgrading @modelcontextprotocol/ext-apps: pnpm --filter server mcp:bridge
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(new URL("../package.json", import.meta.url));
const path = require.resolve("@modelcontextprotocol/ext-apps/app-with-deps");
const source = await readFile(path, "utf8");
const { version } = JSON.parse(
  await readFile(new URL("../node_modules/@modelcontextprotocol/ext-apps/package.json", import.meta.url), "utf8"),
);
await writeFile(
  new URL("../src/mcp/bridge.generated.ts", import.meta.url),
  `// Generated by scripts/build-widget-bridge.mjs from @modelcontextprotocol/ext-apps ${version}; do not edit.\nexport const BRIDGE_VERSION = ${JSON.stringify(version)};\nexport const BRIDGE_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log(`bridge ${version}: ${source.length} bytes`);
